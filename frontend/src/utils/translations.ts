  if (lang === 'ta' && item.descriptionTamil) return item.descriptionTamil;
  if (lang === 'hi' && item.descriptionHindi) return item.descriptionHindi;
  if (lang === 'te' && item.descriptionTelugu) return item.descriptionTelugu;
